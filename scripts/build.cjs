const fs = require('node:fs');
const path = require('node:path');
const { validate } = require('../core.js');
const root = path.join(__dirname, '..');
const source = validate(JSON.parse(fs.readFileSync(path.join(root, 'data/resources.json'), 'utf8')));
const content = '// Generated by npm run build. Edit data/resources.json instead.\n' +
  'globalThis.RESOURCE_DATA = ' + JSON.stringify(source).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029') + ';\n';
const target = path.join(root, 'data/resources.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content) {
    console.error('数据快照未同步，请运行 npm run build'); process.exitCode = 1;
  } else console.log(`数据一致：${source.resources.length} 条`);
} else { fs.writeFileSync(target, content); console.log(`构建完成：${source.resources.length} 条`); }
